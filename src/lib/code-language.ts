const TS_JS_CONFIG_RE = /^(?:tsconfig|jsconfig)(?:\..+)?\.json$/;

export function detectCodeLanguage(filePath: string): BundledLanguage | null {
  const trimmed = filePath.trim();
  if (!trimmed) return null;
  const sepIndex = Math.max(trimmed.lastIndexOf('/'), trimmed.lastIndexOf('\\'));
  const basename = (sepIndex >= 0 ? trimmed.slice(sepIndex + 1) : trimmed).toLowerCase();
  if (!basename) return null;

  const special = SPECIAL_FILENAME_LANG[basename];
  if (special) return special;
  if (TS_JS_CONFIG_RE.test(basename)) return 'jsonc';
  if (basename.startsWith('dockerfile.') || basename.startsWith('containerfile.')) {
    return 'dockerfile';
  }
  if (basename.startsWith('.env.')) return 'dotenv';

  const dot = basename.lastIndexOf('.');
  if (dot <= 0 || dot === basename.length - 1) return null;
  return EXTENSION_LANG[basename.slice(dot + 1)] ?? null;
}
